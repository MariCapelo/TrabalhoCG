def desenhar_texto(tela, texto, x, y, escala, cor):
    offset = 0

    for char in texto:
        matriz = LETRAS.get(char)

        if not matriz:
            continue

        for lin in range(len(matriz)):
            for col in range(len(matriz[lin])):
                if matriz[lin][col] == "1":
                    for i in range(escala):
                        for j in range(escala):
                            setPixel(
                                tela,
                                x + offset + col*escala + i,
                                y + lin*escala + j,
                                cor
                            )

        offset += escala * 4